// Gen writes the list of DevTools protocol command and event names defined by
// the cdproto version this module depends on.
//
// cdproto declares every name as an untyped string constant in its cdproto.go,
// so the names cannot be enumerated at run time. Gen locates the module with
// go list and parses that file.
//
// Usage:
//
//	go run ./internal/cdpproto/gen -o methods.txt
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

func main() {
	log.SetFlags(0)
	log.SetPrefix("cdpproto/gen: ")
	out := flag.String("o", "methods.txt", "output file")
	flag.Parse()

	dir, version, err := moduleDir("github.com/chromedp/cdproto")
	if err != nil {
		log.Fatal(err)
	}
	names, err := protocolNames(dir)
	if err != nil {
		log.Fatal(err)
	}
	if len(names) == 0 {
		log.Fatalf("no protocol names found in %s; the cdproto layout may have changed", dir)
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "# Code generated by internal/cdpproto/gen. DO NOT EDIT.\n")
	fmt.Fprintf(&buf, "# github.com/chromedp/cdproto %s\n", version)
	for _, n := range names {
		fmt.Fprintln(&buf, n)
	}
	if err := os.WriteFile(*out, buf.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Fprintf(os.Stderr, "wrote %s: %d names from cdproto %s\n", *out, len(names), version)
}

// moduleDir returns the local directory and version of the named module.
func moduleDir(mod string) (dir, version string, err error) {
	cmd := exec.Command("go", "list", "-m", "-f", "{{.Dir}}\t{{.Version}}", mod)
	out, err := cmd.Output()
	if err != nil {
		return "", "", fmt.Errorf("locate %s: %w", mod, err)
	}
	dir, version, ok := strings.Cut(strings.TrimSpace(string(out)), "\t")
	if !ok || dir == "" {
		return "", "", fmt.Errorf("locate %s: unexpected go list output %q", mod, out)
	}
	return dir, version, nil
}

// protocolNames returns the method names declared as string constants
// anywhere under root. Events are declared centrally in cdproto.go, but each
// command is declared in its own domain package, so the whole module is
// walked rather than a single file.
func protocolNames(root string) ([]string, error) {
	seen := make(map[string]bool)
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		fset := token.NewFileSet()
		f, err := parser.ParseFile(fset, path, nil, 0)
		if err != nil {
			return fmt.Errorf("parse %s: %w", path, err)
		}
		ast.Inspect(f, func(n ast.Node) bool {
			lit, ok := n.(*ast.BasicLit)
			if !ok || lit.Kind != token.STRING {
				return true
			}
			if s, err := strconv.Unquote(lit.Value); err == nil && isMethodName(s) {
				seen[s] = true
			}
			return true
		})
		return nil
	})
	if err != nil {
		return nil, err
	}
	names := make([]string, 0, len(seen))
	for n := range seen {
		names = append(names, n)
	}
	sort.Strings(names)
	return names, nil
}

func isMethodName(s string) bool {
	domain, member, ok := strings.Cut(s, ".")
	if !ok || domain == "" || member == "" || strings.Contains(member, ".") {
		return false
	}
	return isUpper(rune(domain[0])) && isLower(rune(member[0])) && isAlnum(domain) && isAlnum(member)
}

func isUpper(r rune) bool { return r >= 'A' && r <= 'Z' }
func isLower(r rune) bool { return r >= 'a' && r <= 'z' }

func isAlnum(s string) bool {
	for _, r := range s {
		if !isUpper(r) && !isLower(r) && (r < '0' || r > '9') {
			return false
		}
	}
	return true
}
